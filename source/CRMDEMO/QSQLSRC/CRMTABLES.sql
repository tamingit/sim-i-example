-- ==================================================================
-- CRMTABLES - Create the CRM demo tables in library CRMDEMO
-- Run:  RUNSQLSTM SRCFILE(CRMDEMO/QSQLSRC) SRCMBR(CRMTABLES)
--                 COMMIT(*NONE) NAMING(*SQL)
-- Column names are kept to 10 characters so system and SQL names
-- are the same.
-- ==================================================================
SET SCHEMA CRMDEMO;

-- CRM users: profiles that own customers and receive tasks.
-- Programs register the signed-on user here automatically.
CREATE TABLE CRMUSER (
  USERID    CHAR(10)  NOT NULL PRIMARY KEY,
  FULLNAME  CHAR(30)  NOT NULL DEFAULT '',
  EMAIL     CHAR(60)  NOT NULL DEFAULT '',
  LASTSEEN  TIMESTAMP NOT NULL DEFAULT CURRENT TIMESTAMP
);
LABEL ON TABLE CRMUSER IS 'CRM Demo - Users';

-- Code tables used by the F4 prompt window
CREATE TABLE CRMCODE (
  CODETYPE  CHAR(10)  NOT NULL,
  CODE      CHAR(10)  NOT NULL,
  DESCR     CHAR(30)  NOT NULL DEFAULT '',
  SEQ       SMALLINT  NOT NULL DEFAULT 0,
  PRIMARY KEY (CODETYPE, CODE)
);
LABEL ON TABLE CRMCODE IS 'CRM Demo - Code values';

CREATE TABLE CUSTOMER (
  CUSTID    INTEGER   GENERATED BY DEFAULT AS IDENTITY
                      (START WITH 1001) NOT NULL PRIMARY KEY,
  NAME      CHAR(40)  NOT NULL DEFAULT '',
  STATUS    CHAR(1)   NOT NULL DEFAULT 'P',
  INDUSTRY  CHAR(10)  NOT NULL DEFAULT '',
  ADDR1     CHAR(40)  NOT NULL DEFAULT '',
  CITY      CHAR(25)  NOT NULL DEFAULT '',
  STATE     CHAR(2)   NOT NULL DEFAULT '',
  ZIP       CHAR(10)  NOT NULL DEFAULT '',
  PHONE     CHAR(15)  NOT NULL DEFAULT '',
  WEBSITE   CHAR(40)  NOT NULL DEFAULT '',
  OWNER     CHAR(10)  NOT NULL DEFAULT '',
  CRTUSER   CHAR(10)  NOT NULL DEFAULT '',
  CRTTS     TIMESTAMP NOT NULL DEFAULT CURRENT TIMESTAMP,
  CHGUSER   CHAR(10)  NOT NULL DEFAULT '',
  CHGTS     TIMESTAMP NOT NULL GENERATED ALWAYS
            FOR EACH ROW ON UPDATE AS ROW CHANGE TIMESTAMP
);
LABEL ON TABLE CUSTOMER IS 'CRM Demo - Customers';
CREATE INDEX CUSTI1 ON CUSTOMER (NAME);
CREATE INDEX CUSTI2 ON CUSTOMER (OWNER, STATUS);

CREATE TABLE CONTACT (
  CONTID    INTEGER   GENERATED BY DEFAULT AS IDENTITY
                      (START WITH 1) NOT NULL PRIMARY KEY,
  CUSTID    INTEGER   NOT NULL,
  FIRSTNAME CHAR(20)  NOT NULL DEFAULT '',
  LASTNAME  CHAR(25)  NOT NULL DEFAULT '',
  TITLE     CHAR(30)  NOT NULL DEFAULT '',
  PHONE     CHAR(15)  NOT NULL DEFAULT '',
  EMAIL     CHAR(60)  NOT NULL DEFAULT '',
  ISPRIMARY CHAR(1)   NOT NULL DEFAULT 'N',
  CRTUSER   CHAR(10)  NOT NULL DEFAULT '',
  CRTTS     TIMESTAMP NOT NULL DEFAULT CURRENT TIMESTAMP,
  CHGUSER   CHAR(10)  NOT NULL DEFAULT '',
  CHGTS     TIMESTAMP NOT NULL GENERATED ALWAYS
            FOR EACH ROW ON UPDATE AS ROW CHANGE TIMESTAMP
);
LABEL ON TABLE CONTACT IS 'CRM Demo - Contacts';
CREATE INDEX CONTI1 ON CONTACT (CUSTID, LASTNAME);

-- Activities: calls, meetings, emails, notes and tasks.
-- DUEDATE / DONEDATE of 0001-01-01 means "none".
CREATE TABLE ACTIVITY (
  ACTID     INTEGER   GENERATED BY DEFAULT AS IDENTITY
                      (START WITH 1) NOT NULL PRIMARY KEY,
  CUSTID    INTEGER   NOT NULL,
  CONTID    INTEGER   NOT NULL DEFAULT 0,
  ACTTYPE   CHAR(5)   NOT NULL DEFAULT 'NOTE',
  SUBJECT   CHAR(50)  NOT NULL DEFAULT '',
  NOTES     CHAR(180) NOT NULL DEFAULT '',
  ACTDATE   DATE      NOT NULL DEFAULT CURRENT DATE,
  DUEDATE   DATE      NOT NULL DEFAULT '0001-01-01',
  PRIORITY  CHAR(1)   NOT NULL DEFAULT 'M',
  ASSIGNTO  CHAR(10)  NOT NULL DEFAULT '',
  DONE      CHAR(1)   NOT NULL DEFAULT 'N',
  DONEDATE  DATE      NOT NULL DEFAULT '0001-01-01',
  CRTUSER   CHAR(10)  NOT NULL DEFAULT '',
  CRTTS     TIMESTAMP NOT NULL DEFAULT CURRENT TIMESTAMP,
  CHGUSER   CHAR(10)  NOT NULL DEFAULT '',
  CHGTS     TIMESTAMP NOT NULL GENERATED ALWAYS
            FOR EACH ROW ON UPDATE AS ROW CHANGE TIMESTAMP
);
LABEL ON TABLE ACTIVITY IS 'CRM Demo - Activities and tasks';
CREATE INDEX ACTI1 ON ACTIVITY (CUSTID, ACTDATE);
CREATE INDEX ACTI2 ON ACTIVITY (ASSIGNTO, DONE, DUEDATE);

-- Opportunities. STAGE: 1=Lead 2=Qualified 3=Proposal
--                       4=Negotiation 5=Won 6=Lost
CREATE TABLE OPPTY (
  OPPID     INTEGER   GENERATED BY DEFAULT AS IDENTITY
                      (START WITH 5001) NOT NULL PRIMARY KEY,
  CUSTID    INTEGER   NOT NULL,
  OPPNAME   CHAR(40)  NOT NULL DEFAULT '',
  STAGE     CHAR(1)   NOT NULL DEFAULT '1',
  AMOUNT    DECIMAL(11, 2) NOT NULL DEFAULT 0,
  PROB      SMALLINT  NOT NULL DEFAULT 10,
  CLOSEDATE DATE      NOT NULL DEFAULT CURRENT DATE,
  OWNER     CHAR(10)  NOT NULL DEFAULT '',
  CRTUSER   CHAR(10)  NOT NULL DEFAULT '',
  CRTTS     TIMESTAMP NOT NULL DEFAULT CURRENT TIMESTAMP,
  CHGUSER   CHAR(10)  NOT NULL DEFAULT '',
  CHGTS     TIMESTAMP NOT NULL GENERATED ALWAYS
            FOR EACH ROW ON UPDATE AS ROW CHANGE TIMESTAMP
);
LABEL ON TABLE OPPTY IS 'CRM Demo - Opportunities';
CREATE INDEX OPPI1 ON OPPTY (CUSTID);
CREATE INDEX OPPI2 ON OPPTY (STAGE, CLOSEDATE);

-- Event log: every change writes a row. The live dashboard polls
-- this table to refresh itself and to alert users (FORUSER).
CREATE TABLE CRMEVENT (
  EVTID     BIGINT    GENERATED ALWAYS AS IDENTITY
                      (START WITH 1) NOT NULL PRIMARY KEY,
  EVTTS     TIMESTAMP NOT NULL DEFAULT CURRENT TIMESTAMP,
  EVTUSER   CHAR(10)  NOT NULL DEFAULT '',
  EVTTYPE   CHAR(8)   NOT NULL DEFAULT '',
  CUSTID    INTEGER   NOT NULL DEFAULT 0,
  FORUSER   CHAR(10)  NOT NULL DEFAULT '',
  EVTTEXT   CHAR(80)  NOT NULL DEFAULT ''
);
LABEL ON TABLE CRMEVENT IS 'CRM Demo - Event log';
CREATE INDEX EVTI1 ON CRMEVENT (FORUSER, EVTID);
